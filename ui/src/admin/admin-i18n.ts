const DICTIONARIES = { en, ru } as const;

/**
 * Admin translation hook — `t("admin.users.title")` plus `{param}`
 * interpolation, falling back to English for any missing Russian key.
 */
export function useAdminT(): (
  key: AdminMessageKey,
  params?: Record<string, string | number>,
) => string {
  const { lang } = useI18n();
  return useCallback(
    (key, params = {}) => {
      const template =
        lang === "ru" ? (ru[key] ?? en[key]) : (en[key] ?? ru[key]);
      return template.replace(/\{(\w+)\}/g, (match, name: string) =>
        params[name] === undefined ? match : String(params[name]),
      );
    },
    [lang],
  );
}

/** Non-hook access for tests and non-component modules. */
export function adminMessage(
  key: AdminMessageKey,
  lang: "en" | "ru",
  params: Record<string, string | number> = {},
): string {
  const template = DICTIONARIES[lang][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] === undefined ? match : String(params[name]),
  );
}
